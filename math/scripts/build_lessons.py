"""Generate offline lesson content from the canonical workbook; --check detects drift."""
from pathlib import Path
import argparse
import hashlib
import json
import math
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'hht/docs/workbook/math.md'
OUTPUT = ROOT / 'math/lessons.js'


def generate(source: str) -> str:
    if source.count('<a id="math-course"></a>') != 1:
        raise ValueError('Expected exactly one mathematics chapter')
    chapter = source.split('<a id="math-course"></a>', 1)[1]
    policy = re.search(r'^### 計算の取り組み方\n([\s\S]*?)(?=^<a id="math-foundation")', chapter, re.MULTILINE)
    if policy is None or not policy.group(1).strip():
        raise ValueError('Missing calculation policy')
    pattern = r'^#### ([BA]\d{2}) (.+)\n([\s\S]*?)(?=^<a id="math-|^### |\Z)'
    lessons = []
    for match in re.finditer(pattern, chapter, re.MULTILINE):
        code, title, body = match.groups()
        if '**依頼' not in body or '**完成条件' not in body and '完成条件：**' not in body:
            raise ValueError(f'{code}: missing request or acceptance conditions')
        fields = {}
        for label, key in [('読み取り確認', 'question'), ('確認値', 'answer'), ('確かめ方', 'explanation')]:
            field = re.search(rf'^\*\*{label}：\*\* (.+)$', body, re.MULTILINE)
            if field is None:
                raise ValueError(f'{code}: missing reading check {label}')
            fields[key] = field.group(1).strip()
        fields['answer'] = float(fields['answer'])
        if not math.isfinite(fields['answer']):
            raise ValueError(f'{code}: reading check answer must be finite')
        reasoning = []
        cases = list(re.finditer(r'^##### 計算を確かめる：(.+)\n([\s\S]*?)(?=^##### 計算を確かめる：|\Z)', body, re.MULTILINE))
        for case in cases:
            item = {'title': case.group(1).strip()}
            for label, key in [('考える問い', 'question'), ('選択肢A', 'A'), ('選択肢B', 'B'), ('選択肢C', 'C'), ('判断', 'correct'), ('解答と理由', 'explanation'), ('評価の観点', 'rubric')]:
                field = re.search(rf'^\*\*{label}：\*\* (.+)$', case.group(2), re.MULTILINE)
                if field is None:
                    raise ValueError(f'{code}: missing reasoning field {label}')
                item[key] = field.group(1).strip()
            if item['correct'] not in ('A', 'B', 'C'):
                raise ValueError(f'{code}: invalid reasoning choice')
            reasoning.append(item)
        if cases:
            body = body[:cases[0].start()]
        lessons.append({'id': code, 'title': title.strip(), 'body': body.strip(), 'check': fields, 'reasoning': reasoning})
    expected = [f'B{i:02}' for i in range(1, 19)] + [f'A{i:02}' for i in range(1, 11)]
    if [item['id'] for item in lessons] != expected:
        raise ValueError('Expected B01-B18 and A01-A10 in order')
    digest = hashlib.sha256(chapter.encode('utf-8')).hexdigest()
    return '// Generated by scripts/build_lessons.py; edit the canonical workbook.\n' + \
        'globalThis.MATH_LESSONS = ' + json.dumps(lessons, ensure_ascii=False, indent=2) + ';\n' + \
        'globalThis.MATH_CALCULATION_POLICY = ' + json.dumps(policy.group(1).strip(), ensure_ascii=False) + ';\n' + \
        f'globalThis.MATH_SOURCE_SHA256 = "{digest}";\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(SOURCE.read_text(encoding='utf-8'))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
            raise SystemExit('FAIL: lessons.js is stale; run python math/scripts/build_lessons.py')
        print('PASS: generated content matches all 28 workbook units')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
        print('PASS: generated math/lessons.js (28 units)')


if __name__ == '__main__':
    main()
